<?php
global $DIC;
$db = $DIC->database();

if (!$db->tableExists('examconnguard_settings')) {
    $db->createTable('examconnguard_settings', [
        'test_id' => [
            'type'    => 'integer',
            'length'  => 4,
            'notnull' => true,
        ],
        'enabled' => [
            'type'    => 'integer',
            'length'  => 1,
            'notnull' => true,
            'default' => 0,
        ],
        'updated_at' => [
            'type'    => 'timestamp',
            'notnull' => false,
        ],
    ]);
    $db->addPrimaryKey('examconnguard_settings', ['test_id']);
}
